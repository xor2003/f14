#!/usr/bin/env python3
# ghidra2mzmap.py — build an mzretools-format map from a Ghidra dump of a
# 16-bit MZ executable (funcs.txt + ranges.txt + memmap.txt produced by
# DumpFuncs.java). Optionally applies names from a matches file or a
# rename list.
#
# Map syntax (mzretools):
#   Size <hex>                      load image size in bytes
#   <SegName> CODE <para>           segment declaration (paragraph base)
#   <name>: <Seg> NEAR|FAR <start>-<end> R<a>-<b> ...
#
# Segment values are PARAGRAPHS (byte offset /16). Routine extents are
# segment-relative hex offsets. R-blocks list the function's instruction
# ranges (embedded data excluded); routine extents are clipped to the next
# routine's first block so extents never collide. Blocks that Ghidra
# attributes to a function but that physically live outside its code
# segment are dropped.
#
# usage: ghidra2mzmap.py memmap.txt ranges.txt size_hex [names.txt] > out.map
#   names.txt format: "<para_hex>:<off_hex> <name>" per line (gold-style
#   Ghidra addresses without the 0x1000 base — i.e. plain para:off).

import bisect
import re
import sys
import collections


def main():
    memmap, ranges, size_hex = sys.argv[1], sys.argv[2], sys.argv[3]
    names = {}
    if len(sys.argv) > 4:
        for l in open(sys.argv[4]):
            m = re.match(r'([0-9a-f]+):([0-9a-f]+) (\S+)', l)
            if m:
                names[(int(m.group(1), 16), int(m.group(2), 16))] = m.group(3)

    segs = []                                   # (name, para)
    for l in open(memmap):
        m = re.match(r'(CODE_\d+|Code\d+) ([0-9a-f]+):([0-9a-f]+)', l)
        if m:
            segs.append((m.group(1), int(m.group(2), 16) - 0x1000))
    segs.sort(key=lambda x: x[1])
    paras = [s for _, s in segs]

    funcs = []
    for l in open(ranges):
        p = l.split()
        if not p:
            continue
        seg, off = p[0].split(':')
        blocks = [(int(a, 16) - 0x10000, int(b, 16) - 0x10000)
                  for a, b in (x.split('-') for x in p[1:])]
        funcs.append((int(seg, 16) - 0x1000, int(off, 16), blocks))

    def codefor(pseg):
        i = bisect.bisect_right(paras, pseg) - 1
        return segs[i] if i >= 0 else None

    print(f'Size {size_hex}')
    print('# generated by ghidra2mzmap.py')
    for n, s in segs:
        print(f'{n} CODE {s:04x}')

    fby = collections.defaultdict(list)
    for seg, off, blocks in funcs:
        c = codefor(seg)
        if not c:
            continue
        n, s = c
        lo = s << 4
        idx = paras.index(s)
        hi = paras[idx + 1] << 4 if idx + 1 < len(paras) else 1 << 24
        rel = sorted(set((a - lo, b - lo) for a, b in blocks if lo <= a < hi))
        rel = [(a, min(b, hi - lo)) for a, b in rel if b > a >= 0]
        if not rel:
            continue
        fby[n].append((seg - s, off, tuple(rel)))

    used = set()
    for n, s in segs:
        fl = sorted(set(fby[n]), key=lambda t: t[2][0][0])
        starts = sorted(r[2][0][0] for r in fl)
        for so, off, rel in fl:
            start, end = rel[0][0], rel[-1][1] - 1
            later = [x for x in starts if x > start]
            if later and end >= later[0]:
                end = later[0] - 1
            if end < start:
                end = start
            fin = []
            for a, b in rel:
                pts = [a] + [x for x in starts if a < x < b] + [b]
                fin += [(x, y) for x, y in zip(pts, pts[1:]) if y > x]
            nm = names.get((s + so, off), f'FUN_{s + so:04x}_{off:04x}')
            if nm in used:
                nm = f'{nm}_d{s + so:04x}{off:04x}'
            used.add(nm)
            bs = ' '.join(f'R{a:04x}-{b - 1:04x}' for a, b in fin)
            print(f'{nm}: {n} FAR {start:04x}-{end:04x} {bs}')


if __name__ == '__main__':
    main()
