#!/usr/bin/env python3
# linkmap2mzmap.py — build an mzretools-format map straight from a
# Microsoft LINK .MAP (publics + segment table).  Unlike the Ghidra-derived
# maps, extents come from consecutive public addresses inside each CODE
# segment, so functions are never truncated mid-body.
#
# usage: linkmap2mzmap.py F14.MAP size_hex > out.map
#
# Emitted syntax (mzretools):
#   Size <hex>
#   <SegName> CODE <para>
#   <name>: <Seg> FAR <start>-<end> R<a>-<b>

import re
import sys
import collections


def main():
    map_path, size_hex = sys.argv[1], sys.argv[2]
    prefer = set()
    if len(sys.argv) > 3:
        for l in open(sys.argv[3]):
            prefer.add(l.split()[0])

    # --- segment table: " <start>H <stop>H <len>H NAME CLASS" -----------
    segs = []  # (start_byte, stop_byte, name, class)
    seg_re = re.compile(
        r'^\s+([0-9A-Fa-f]+)H\s+([0-9A-Fa-f]+)H\s+([0-9A-Fa-f]+)H\s+'
        r'(\S+)\s+(\S+)\s*$')
    in_table = False
    for l in open(map_path, errors='replace'):
        if 'Start' in l and 'Stop' in l and 'Length' in l:
            in_table = True
            continue
        if in_table:
            m = seg_re.match(l)
            if m:
                segs.append((int(m.group(1), 16), int(m.group(2), 16),
                             m.group(4), m.group(5)))
            elif l.strip() == '' or 'Group' in l or 'Publics' in l:
                if 'Group' in l or 'Publics' in l:
                    break

    # --- publics: " <seg>:<ofs>  name" ---------------------------------
    # The map prints the table twice (by Name, by Value) — dedupe.
    pub_re = re.compile(r'^\s+([0-9A-Fa-f]+):([0-9A-Fa-f]+)\s+(\S+)\s*$')
    pubs = []
    pubset = set()
    for l in open(map_path, errors='replace'):
        m = pub_re.match(l)
        if m:
            key = (int(m.group(1), 16) * 16 + int(m.group(2), 16),
                   m.group(3))
            if key not in pubset:
                pubset.add(key)
                pubs.append(key)

    # bucket publics into code segments by absolute address; multiple
    # segments can share a start (e.g. empty _DMATRIX_TEXT vs MPS_CODE),
    # so walk back over equal starts to find the one that contains it.
    segs.sort()
    byseg = collections.defaultdict(list)
    starts = [s[0] for s in segs]
    import bisect
    for absa, name in pubs:
        i = bisect.bisect_right(starts, absa) - 1
        # walk back over same-start segments to find the containing one
        while i >= 0 and absa > segs[i][1] and \
                i > 0 and starts[i - 1] == starts[i]:
            i -= 1
        if i < 0:
            continue
        s = segs[i]
        if s[3].upper() != 'CODE' or absa > s[1]:
            continue
        # LINK map public seg:ofs are para-relative; byte-aligned
        # segments start mid-para, so normalize against the para base.
        byseg[i].append((absa - (s[0] & ~0xf), name))

    print(f'Size {size_hex}')
    print('# generated by linkmap2mzmap.py from ' + map_path)
    used = set()
    code_idx = [i for i, s in enumerate(segs) if s[3].upper() == 'CODE']
    for i in code_idx:
        st = segs[i][0]
        print(f'{segs[i][2]} CODE {st // 16:04x}')
    # DGROUP anchor so mzdiff can resolve DS-relative data refs;
    # NULL/BEGDATA starts DGROUP in the link map.
    for i, s in enumerate(segs):
        if s[3].upper() in ('BEGDATA', 'DATA') and s[2] == 'NULL':
            print(f'DGROUP DATA {s[0] // 16:04x}')
            break
    for i in code_idx:
        st, sp, sname, _ = segs[i]
        entries = sorted(byseg.get(i, []))
        # alias publics share an offset; emit one name per offset so
        # extents never overlap (mzdiff rejects collisions).  Prefer a
        # name listed in the optional names-file argument.
        ded = []
        for off, name in entries:
            if ded and ded[-1][0] == off:
                if name in prefer and ded[-1][1] not in prefer:
                    ded[-1] = (off, name)
                continue
            ded.append((off, name))
        entries = ded
        segend = sp - (st & ~0xf)          # stop is inclusive, para-rel
        for idx, (off, name) in enumerate(entries):
            end = entries[idx + 1][0] - 1 if idx + 1 < len(entries) \
                else segend
            if end < off:
                end = off
            nm = name
            if nm in used:
                nm = f'{name}_d{st + off:05x}'
            used.add(nm)
            print(f'{nm}: {sname} FAR {off:04x}-{end:04x} '
                  f'R{off:04x}-{end:04x}')


if __name__ == '__main__':
    main()
